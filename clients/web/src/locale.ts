export function channelDisplayName(language: Language, id: string, fallback?: string) {
  return Object.hasOwn(channelNames, id) ? channelNames[id][language] : fallback || id;
}

export function channelConfigOptionName(language: Language, value: string) {
  return Object.hasOwn(configOptionNames, value) ? configOptionNames[value][language] : value;
}

export function translate(language: Language, key: string, values?: Record<string, string | number>) {
  const text = language === "en" ? english[key] : chinese[key];
  const template = typeof text === "string" ? text : key;
  return template.replace(/\{([a-zA-Z]+)\}/g, (match, name: string) => String(values?.[name] ?? match));
}

export function chooseLanguage(stored: string | null, system: string): Language {
  if (stored === "zh-CN" || stored === "en") return stored;
  return /^zh(?:-|$)/i.test(system) ? "zh-CN" : "en";
}

export function chooseTheme(stored: string | null): ThemePreference {
  return stored === "light" || stored === "dark" ? stored : "system";
}

export function resolveTheme(preference: ThemePreference, darkSystem: boolean): "light" | "dark" {
  return preference === "system" ? darkSystem ? "dark" : "light" : preference;
}
